export type ProjectSection =
  | { kind: 'text'; title?: string; body: string[] }
  | { kind: 'list'; title?: string; items: string[] }
  | { kind: 'quote'; text: string; author?: string }
  | { kind: 'hypotheses'; title?: string; items: { hypothesis: string; result: string; insight: string }[] }
  | { kind: 'tools'; title?: string; items: { name: string; logo: string; description: string }[] }
  | {
      kind: 'gallery';
      images?: { src: string; alt?: string; aspect?: 'wide' | 'tall' | 'square' }[];
      // Explicit rows: each inner array is one row, all items share equal width.
      // Use when the editor wants precise control over which screens sit next to each other.
      rows?: string[][];
      // 'fit' = stack each image at natural aspect, full width, no crop (good for web shots).
      // 'crop' (default for rows / legacy) = uniform aspect frame, object-cover.
      layout?: 'fit' | 'crop';
      // Frame aspect when layout='crop' and rows are used. Defaults to tall (9/16) for mobile screens.
      rowAspect?: 'tall' | 'wide' | 'square';
      // Hard cap on the gallery's outer width in pixels. Currently honored by fit-mode.
      // Default fit-mode width is 768 (max-w-3xl).
      maxWidth?: number;
    };

